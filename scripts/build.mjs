// Builds dist/extension (with generated presets), the extension ZIP, and keeps the Swift catalog
// in sync. `node scripts/build.mjs --check` fails if the committed Swift catalog is stale.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { ROOT, loadCatalog, zoneFile, localeFile, acceptLanguage } from "./catalog.mjs";

const check = process.argv.includes("--check");
const { zones, locales, languages } = loadCatalog();
const version = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version;

const swift = `// GENERATED by scripts/build.mjs from profile/locales.json and Node ICU. Do not edit.
public enum Catalog {
    public static let timeZones: Set<String> = [
${zones.map((z) => `        "${z}",`).join("\n")}
    ]
    public static let locales: [String] = [
${locales.map((l) => `        "${l}",`).join("\n")}
    ]
}
`;
const swiftPath = join(ROOT, "mac/Sources/ProfileCore/Catalog.generated.swift");
if (check) {
  if (!existsSync(swiftPath) || readFileSync(swiftPath, "utf8") !== swift) {
    console.error("Catalog.generated.swift is stale; run npm run build");
    process.exit(1);
  }
  console.log("catalog in sync");
  process.exit(0);
}
writeFileSync(swiftPath, swift);

const out = join(ROOT, "dist/extension");
rmSync(join(ROOT, "dist"), { recursive: true, force: true });
cpSync(join(ROOT, "extension"), out, { recursive: true });
const manifest = JSON.parse(readFileSync(join(out, "manifest.json"), "utf8"));
manifest.version = version;
writeFileSync(join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

mkdirSync(join(out, "presets/tz"), { recursive: true });
mkdirSync(join(out, "presets/locale"), { recursive: true });
for (const z of zones) {
  writeFileSync(join(out, zoneFile(z)), `(self.__claudeLocaleKit ||= {}).timeZone = ${JSON.stringify(z)};\n`);
}
for (const l of locales) {
  writeFileSync(
    join(out, localeFile(l)),
    `(self.__claudeLocaleKit ||= {}).locale = ${JSON.stringify(l)};\nself.__claudeLocaleKit.languages = ${JSON.stringify(languages[l])};\n`,
  );
}
mkdirSync(join(out, "generated"), { recursive: true });
writeFileSync(
  join(out, "generated/catalog.js"),
  `// GENERATED by scripts/build.mjs. Do not edit.
export const TIME_ZONES = Object.freeze(${JSON.stringify(zones)});
export const LOCALES = Object.freeze(${JSON.stringify(locales)});
export const LANGUAGES = Object.freeze(${JSON.stringify(languages)});
export const ACCEPT_LANGUAGE = Object.freeze(${JSON.stringify(Object.fromEntries(locales.map((l) => [l, acceptLanguage(languages[l])])))});
export const zoneFile = (z) => "presets/tz/" + z.replaceAll("/", "__") + ".js";
export const localeFile = (l) => "presets/locale/" + l + ".js";
`,
);
const zip = join(ROOT, `dist/claude-locale-kit-extension-${version}.zip`);
execFileSync("zip", ["-qrX", zip, "."], { cwd: out });
console.log(`built ${out} (${zones.length} zones, ${locales.length} locales) and ${zip}`);
